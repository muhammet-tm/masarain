    if (prev < PE && now >= PE) { slots["sl-sil"].roll.set(slots["sl-sil"].fin, true); tween(250, function (p) { S.connDraw = p; }); }
    if (now > LR && now < DISC) slots["sl-conn"].roll.set(Math.max(0, now - LR).toFixed(1), true);
    if (prev < DISC && now >= DISC) slots["sl-conn"].roll.set(slots["sl-conn"].fin, true);
    if (prev < HOLE.t1 && now >= HOLE.t1) { slots["sl-gap0"].roll.set(slots["sl-gap0"].fin, true); slots["sl-gap1"].roll.set(slots["sl-gap1"].fin, true); pending("sl-gap0", false); }
