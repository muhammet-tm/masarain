  /* ---------- one ticker for every motion on the canvas ---------- */
  var tweens = [], raf = 0, lastTs = 0;
  function kick() { if (!raf) raf = requestAnimationFrame(tick); }
  function tween(ms, update, done, ease) {
    if (reduce || ms <= 0) { update(1); if (done) done(); kick(); return null; }
    var tw = { ms: ms, start: null, update: update, done: done, ease: ease || easeOut, dead: false };
    tweens.push(tw); kick(); return tw;
  }
  function tick(ts) {
    raf = 0;
    var dt = lastTs ? Math.min(0.1, (ts - lastTs) / 1000) : 0; lastTs = ts;
    var busy = false;
    tweens = tweens.filter(function (tw) {
      if (tw.dead) return false;
      if (tw.start === null) tw.start = ts;
      var p = Math.min(1, (ts - tw.start) / tw.ms);
      tw.update(tw.ease(p));
      if (p >= 1) { if (tw.done) tw.done(); return false; }
      busy = true; return true;
    });
    if (S.sweep !== Infinity && !S.paused && !document.hidden) { advance(dt); busy = true; }
    frame();
    if (busy || tweens.length) raf = requestAnimationFrame(tick); else lastTs = 0;
  }

